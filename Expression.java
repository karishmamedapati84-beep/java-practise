//write the following expression in java program: (v(square)-u(square))/2as
class Expression {
    public static void main(String args[]){
        int v,u;
        float a,s;
        v=10;
        u=4;
        a=8;
        s=6;
        float c=(v*v - u*u)/(2*a*s);
        System.out.println(c);
    }
}
