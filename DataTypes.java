class DataTypes{
    public static void main(String args[]){
        byte x=5;
        int y=6;
        short z=8;
        int a=y+z;
        float b=6.54f+x;
        System.out.println(a);
        System.out.println(b);
        
        //increment and Decrement operators
        int i=56;
        //int b=i++;
        int j=67;
        int c=++j;
        System.out.println(c);
        System.out.println(i++);
        System.out.println(i);
        System.out.println(++i);
        System.out.println(i);
    }
}